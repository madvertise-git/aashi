-- Foundation tables: users, sessions, agencies, memberships, accounts, contacts, outbox.
-- Every table has row-level security switched on AND forced, so even the table
-- owner is filtered. A query that forgets its filter returns nothing.

CREATE EXTENSION IF NOT EXISTS citext;
--> statement-breakpoint

-- ---------------------------------------------------------------------------
-- Request context. The API sets these three settings at the start of each
-- transaction; every policy below reads them. Unset means "no access".
-- ---------------------------------------------------------------------------
CREATE FUNCTION app_user_id() RETURNS uuid LANGUAGE sql STABLE AS
$$ SELECT nullif(current_setting('app.user_id', true), '')::uuid $$;
--> statement-breakpoint
CREATE FUNCTION app_agency_id() RETURNS uuid LANGUAGE sql STABLE AS
$$ SELECT nullif(current_setting('app.agency_id', true), '')::uuid $$;
--> statement-breakpoint
CREATE FUNCTION app_account_id() RETURNS uuid LANGUAGE sql STABLE AS
$$ SELECT nullif(current_setting('app.account_id', true), '')::uuid $$;
--> statement-breakpoint

-- ---------------------------------------------------------------------------
-- Tables. IDs are UUIDv7 generated by the API. All times are UTC.
