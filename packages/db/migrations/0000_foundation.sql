-- A user sees their own row, and the people in the agency they are working in.
CREATE POLICY users_self ON users FOR ALL
  USING (id = app_user_id());
--> statement-breakpoint
CREATE POLICY users_agency_peers ON users FOR SELECT
  USING (EXISTS (
    SELECT 1 FROM memberships m
    WHERE m.user_id = users.id AND m.agency_id = app_agency_id()
  ));
--> statement-breakpoint
CREATE POLICY sessions_own ON sessions FOR ALL
  USING (user_id = app_user_id());
--> statement-breakpoint

-- A user sees the agencies they belong to. Changes need the agency context.
CREATE POLICY agencies_select ON agencies FOR SELECT
  USING (
    id = app_agency_id()
    OR EXISTS (
      SELECT 1 FROM memberships m
      WHERE m.agency_id = agencies.id AND m.user_id = app_user_id()
    )
  );
--> statement-breakpoint
CREATE POLICY agencies_insert ON agencies FOR INSERT
  WITH CHECK (id = app_agency_id() AND app_user_id() IS NOT NULL);
--> statement-breakpoint
CREATE POLICY agencies_update ON agencies FOR UPDATE
  USING (id = app_agency_id());
--> statement-breakpoint

CREATE POLICY memberships_select ON memberships FOR SELECT
  USING (user_id = app_user_id() OR agency_id = app_agency_id());
--> statement-breakpoint
CREATE POLICY memberships_insert ON memberships FOR INSERT
  WITH CHECK (agency_id = app_agency_id());
--> statement-breakpoint
CREATE POLICY memberships_update ON memberships FOR UPDATE
  USING (agency_id = app_agency_id());
--> statement-breakpoint
CREATE POLICY memberships_delete ON memberships FOR DELETE
  USING (agency_id = app_agency_id());
--> statement-breakpoint

-- The agency is the hard wall.
