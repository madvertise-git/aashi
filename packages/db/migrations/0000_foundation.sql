--> statement-breakpoint
CREATE INDEX memberships_user_id_idx ON memberships (user_id);
--> statement-breakpoint
CREATE TABLE accounts (
  id         uuid PRIMARY KEY,
  agency_id  uuid NOT NULL REFERENCES agencies (id) ON DELETE CASCADE,
  name       text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  -- Lets other tables point at (account, agency) together, so a row can never
  -- be attached to an account in a different agency.
  UNIQUE (id, agency_id)
);
--> statement-breakpoint
CREATE INDEX accounts_agency_id_idx ON accounts (agency_id, id);
--> statement-breakpoint
CREATE TABLE contacts (
  id         uuid PRIMARY KEY,
  agency_id  uuid NOT NULL,
  account_id uuid NOT NULL,
  first_name text NOT NULL,
  last_name  text,
  email      citext,
  -- International format (E.164), e.g. +919876543210.
  phone      text CHECK (phone ~ '^\+[1-9][0-9]{7,14}$'),
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now(),
  FOREIGN KEY (account_id, agency_id) REFERENCES accounts (id, agency_id) ON DELETE CASCADE
);
--> statement-breakpoint
-- Indexes start with the account, matching how every query filters.
