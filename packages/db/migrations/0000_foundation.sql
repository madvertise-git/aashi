-- ---------------------------------------------------------------------------
-- Look-ups that must happen before a tenant is known. Each returns at most one
-- row for an exact key, and is owned by platform_resolver (see bootstrap.sql).
-- These are the only code paths that read past row-level security.
-- ---------------------------------------------------------------------------
CREATE FUNCTION auth_user_by_email(p_email text)
RETURNS TABLE (id uuid, email text, name text, password_hash text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS
$$ SELECT u.id, u.email::text, u.name, u.password_hash FROM users u WHERE u.email = p_email::citext $$;
--> statement-breakpoint
CREATE FUNCTION auth_session(p_token_hash text)
RETURNS TABLE (session_id uuid, user_id uuid)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS
$$ SELECT s.id, s.user_id FROM sessions s WHERE s.token_hash = p_token_hash AND s.expires_at > now() $$;
--> statement-breakpoint
-- "May this user work in this client account, and which agency is it in?"
CREATE FUNCTION auth_account_access(p_user_id uuid, p_account_id uuid)
RETURNS TABLE (agency_id uuid, role text)
LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public, pg_temp AS
$$
  SELECT a.agency_id, m.role
  FROM accounts a
  JOIN memberships m ON m.agency_id = a.agency_id AND m.user_id = p_user_id
  WHERE a.id = p_account_id
$$;
--> statement-breakpoint
REVOKE ALL ON FUNCTION auth_user_by_email(text), auth_session(text), auth_account_access(uuid, uuid) FROM PUBLIC;
--> statement-breakpoint
